  await expect(page.locator('#narrative-width')).toHaveValue('1344');
  await page.locator('#narrative-prompt').fill('My exact environment prompt.\nNegative constraints: literal prose.');
  await page.getByRole('button',{name:'Render edited prompt · 1',exact:true}).click();
  await expect(page.locator('.narrative-slot').first()).toContainText('queued');
  const detail = await (await page.request.get(base)).json();
  const job = Object.values(detail.jobs).find(item=>item.kind==='image');
  const prompt = await readFile(path.join(fixtureRoot,'Queue/File_Proxy/Ask/zet',job.id,'prompt.md'),'utf8');

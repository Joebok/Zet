import {expect,test} from '@playwright/test';
import {mkdir,readFile,writeFile,rename,copyFile} from 'node:fs/promises';
import path from 'node:path';

const fixtureRoot = path.resolve('test-results/dashboard-browser-project');

async function finish(page,base,kind,payload) {
  const detail = await (await page.request.get(base)).json();
  const job = Object.values(detail.jobs).filter(item=>item.kind===kind).at(-1);
  const ask = path.join(fixtureRoot,'Queue/File_Proxy/Ask/zet',job.id);
  const answer = path.join(fixtureRoot,'Queue/File_Proxy/Answer/zet',job.id);
  const manifest = JSON.parse(await readFile(path.join(ask,'ask_manifest.json'),'utf8'));
  await rename(ask,answer);
  if (kind === 'image') await copyFile(path.join(fixtureRoot,'Stories/Alpha-Story/Opening-Scene.png'),path.join(answer,manifest.expected_output));
  else await writeFile(path.join(answer,manifest.expected_output),JSON.stringify(payload));
  await writeFile(path.join(answer,'answer_manifest.json'),JSON.stringify({ask_id:job.id,status:'SUCCESS',expected_output:manifest.expected_output}));
  await writeFile(path.join(answer,'harvest_manifest.json'),'{}');
  return job;
}

